export function providerLabel(id) {
  return PROVIDERS[id]?.label || id;
}

export function providerBaseUrl(providerId, accountId) {
  const base = PROVIDERS[providerId]?.baseUrl || '';
  return base.replace('{account_id}', accountId || '');
}
